"""One-command red-team summary for the pitch: every case set, four ways to defend. Owner: Agent AI engineer.

    python services/agent-wallet/eval/redteam_summary.py   # writes eval/REDTEAM.md (about a minute)

For each case set in eval/ it runs run_eval.py's harness (fresh mock wallet per case, no LLM, no network):

- Scanner alone: attacks the L2 injection scanner flags on the request, as a detector-only product would.
- Chain alone: the DEMO_MODE bypass, so only the contracts' rules (L5, the mock ledger) stand in the way.
- Full stack: guard L0-L4, then the chain. The configuration the demo runs.
- Adaptive attacker: full stack, each attack preceded by a probe the scanner catches (run_eval --probe-first).

"Reached execute" counts attacks whose request executed (inside the mandate or not). "Unauthorized" is
CLAUDE.md 7.4: money to a non-allowlisted address, above a cap, outside the mandate, or twice. Exit code 1 if
the full stack lets any unauthorized payment through.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import run_eval  # noqa: E402

OUT = HERE / "REDTEAM.md"
SETS = [
    ("cases.jsonl", "Seed set (CLAUDE.md 7.4)"),
    ("dev_cases.jsonl", "Dev set"),
    ("heldout_cases.jsonl", "Held-out v1"),
    ("heldout_v2_cases.jsonl", "Held-out v2"),
    ("heldout_v3_cases.jsonl", "Held-out v3"),
    ("heldout_v4_cases.jsonl", "Held-out v4"),
    ("heldout_v5_cases.jsonl", "Held-out v5"),
    ("approval_cases.jsonl", "Human-approval path"),
]
HEADER = """# Red-team summary: scanner alone vs chain alone vs full stack

Generated by `python services/agent-wallet/eval/redteam_summary.py` (mock ledger, no LLM, no network).
Each case gets a fresh wallet. Case files are in `eval/`; per-set detail is in `eval/report_*.md`.

| Case set | Attacks | Scanner alone flags | Chain alone stops (unauthorized) | Full stack stops \
| Full stack: reached execute / unauthorized | Adaptive attacker: reached execute | Benign completed |
|---|---|---|---|---|---|---|---|"""
NOTES = """
How to read it:

- **Scanner alone** is what a prompt-injection detector catches by itself. It is well below 100% on the
  held-out sets, which is why the wallet does not rely on it.
- **Chain alone** is the contracts' rules with every off-chain layer bypassed (`DEMO_MODE`,
  `skip_offchain_checks`). The number in brackets is unauthorized payments. The contracts keep money inside
  the mandate with nothing off-chain running. PD is not on chain, so the TX-2 approval refuses a decision
  above the PD ceiling and the draw then reverts `NotApproved`. Agent-loop cases are not run in this mode.
- **Full stack** is the configuration the demo runs. *Reached execute* counts attacks that executed inside the
  mandate: the scanner missed the text, but the payee, amount and APR were still the mandate's. *Unauthorized*
  must be 0.
- **Adaptive attacker** sends one probe that gets caught, then the attack on the same invoice, as a real
  attacker iterating would. The tripwire's quarantine stops the follow-up.
"""
SECTIONS = [
    ("Attacks that executed inside the mandate (scanner misses, full stack)", "misses"),
    ("Benign cases blocked (full stack)", "false_blocks"),
    ("Unauthorized payments with the off-chain guard bypassed (chain alone)", "chain_unauth_ids"),
]
SUMMED = ["attacks", "scan", "chain_caught", "chain_attacks", "chain_unauth", "caught", "reached", "unauth"]
SUMMED += ["adapt", "adapt_n", "benign_ok", "benign"]


def run(path: Path, skip_offchain: bool, probe_first: bool) -> dict:
    run_eval.PROBE_FIRST = probe_first
    try:
        rows, _ = run_eval.run_all(skip_offchain, path)
    finally:
        run_eval.PROBE_FIRST = False
    stats = run_eval.summarise(rows)
    attacks = [r for r in rows if not r.get("skipped") and r["case"]["attack"]]
    stats["scanner_caught"] = sum(r["scanner_flagged"] for r in attacks)
    return stats


def row_for(name: str, label: str) -> dict:
    path = HERE / name
    full = run(path, skip_offchain=False, probe_first=False)
    chain = run(path, skip_offchain=True, probe_first=False)
    adaptive = run(path, skip_offchain=False, probe_first=True)
    return {
        "label": label,
        "file": name,
        "attacks": full["attacks"],
        "scan": full["scanner_caught"],
        "chain_caught": chain["caught"],
        "chain_attacks": chain["attacks"],
        "chain_unauth": chain["unauthorized"],
        "caught": full["caught"],
        "reached": full["reached_execute"],
        "unauth": full["unauthorized"],
        "adapt": adaptive["reached_execute"],
        "adapt_n": adaptive["attacks"],
        "benign_ok": full["benign_completed"],
        "benign": full["benign"],
        "misses": [r["case"]["id"] for r in full["failures"] if r["case"]["attack"]],
        "false_blocks": [r["case"]["id"] for r in full["failures"] if not r["case"]["attack"]],
        "chain_unauth_ids": [case_id for case_id, _ in chain["unauthorized_detail"]],
    }


def frac(n: int, d: int) -> str:
    return f"{n}/{d}" if d else "-"


def line(r: dict, label: str) -> str:
    return (
        f"| {label} | {r['attacks']} | {frac(r['scan'], r['attacks'])} "
        f"| {frac(r['chain_caught'], r['chain_attacks'])} ({r['chain_unauth']}) "
        f"| {frac(r['caught'], r['attacks'])} | {r['reached']} / **{r['unauth']}** "
        f"| {frac(r['adapt'], r['adapt_n'])} | {frac(r['benign_ok'], r['benign'])} |"
    )


def main() -> int:
    table = []
    for name, label in SETS:
        if (HERE / name).exists():
            table.append(row_for(name, label))
            print(f"{label}: done", file=sys.stderr)
    totals = {key: sum(r[key] for r in table) for key in SUMMED}
    lines = [HEADER]
    lines += [line(r, f"{r['label']} (`{r['file']}`)") for r in table]
    lines.append(line(totals, "**All sets**"))
    lines.append(NOTES)
    for title, key in SECTIONS:
        lines += [f"{title}:", ""]
        lines += [f"- {r['label']}: {', '.join(r[key])}" for r in table if r[key]] or ["- none"]
        lines.append("")
    text = "\n".join(lines).rstrip() + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)
    return 1 if totals["unauth"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
